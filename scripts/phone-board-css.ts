// The phone draws the Mac's own board (BoardView from the desktop renderer),
// so it needs the Mac's board styles too. This copies those rules out of the
// desktop stylesheet into apps/phone/src/mac-board.css. Run it after
// changing the board's styles; a unit test fails while the copy is stale.
//
//   bun run scripts/phone-board-css.ts
import { join } from "node:path";

const root = join(import.meta.dir, "..");
export const DESKTOP_CSS = join(root, "apps/desktop/src/renderer/styles.css");
export const PHONE_CSS = join(root, "apps/phone/src/mac-board.css");

/** Board classes, and what a card uses from elsewhere: buttons, dialogs. */
const WANTED =
  /\.(board-(?!detail-column|column)|count-badge|percent-input|quiet\b|create-button|session-status-unconfirmed|report-|app-dialog|modal|confirmation-content|detail-title|eyebrow)/;

interface Block {
  head: string;
  body: string;
}

function blocks(text: string): Block[] {
  const out: Block[] = [];
  let index = 0;
  while (index < text.length) {
    const skip = /^(\s+|\/\*[\s\S]*?\*\/)/.exec(text.slice(index));
    if (skip) {
      index += skip[0].length;
      continue;
    }
    const open = text.indexOf("{", index);
    if (open < 0) break;
    let depth = 1;
    let end = open + 1;
    while (depth > 0) {
      if (text[end] === "{") depth += 1;
      else if (text[end] === "}") depth -= 1;
      end += 1;
    }
    out.push({
      head: text.slice(index, open).trim(),
      body: text.slice(open + 1, end - 1),
    });
    index = end;
  }
  return out;
}

const LIGHT = '.app[data-theme="light"] ';

/** One selector as the phone needs it, or none. */
function selector(raw: string): string | undefined {
  const text = raw.replace(/\s+/g, " ").trim();
  // The Mac's filled-button and field rules are global there; here they are
  // for the board only.
  if (/^(button:not\(|input\b|textarea\b|select\b)/.test(text))
    return `:where(.mac-board) ${text}`;
  return WANTED.test(text) && !text.includes("board-detail-column")
    ? text
    : undefined;
}

/**
 * The selectors of a rule worth copying, split by theme: the Mac marks its
 * light theme on `.app`, the phone follows the system's.
 */
function selectors(head: string): { dark: string[]; light: string[] } {
  const dark: string[] = [];
  const light: string[] = [];
  for (const raw of splitSelectors(head)) {
    const text = raw.replace(/\s+/g, " ").trim();
    if (text.startsWith(LIGHT)) {
      const kept = selector(text.slice(LIGHT.length));
      if (kept) light.push(kept);
    } else if (!text.startsWith(".app")) {
      const kept = selector(text);
      if (kept) dark.push(kept);
    }
  }
  return { dark, light };
}

/** Splits on commas outside parentheses, as in `button:not(.a, .b)`. */
function splitSelectors(head: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let start = 0;
  for (let index = 0; index < head.length; index += 1) {
    if (head[index] === "(") depth += 1;
    else if (head[index] === ")") depth -= 1;
    else if (head[index] === "," && depth === 0) {
      out.push(head.slice(start, index));
      start = index + 1;
    }
  }
  out.push(head.slice(start));
  return out;
}

export function phoneBoardCss(desktop: string): string {
  const out: string[] = [
    "/* Generated by scripts/phone-board-css.ts from the desktop's",
    "   styles.css. Do not edit; run the script after changing the board. */",
  ];
  const light: string[] = [];
  for (const { head, body } of blocks(desktop)) {
    if (head.startsWith("@keyframes")) continue;
    if (head.startsWith("@")) {
      const inner = blocks(body).flatMap(({ head: inside, body: rules }) => {
        const { dark } = selectors(inside);
        return dark.length ? [`  ${dark.join(", ")} {${rules}}`] : [];
      });
      if (inner.length) out.push(`${head} {\n${inner.join("\n")}\n}`);
      continue;
    }
    const kept = selectors(head);
    if (kept.dark.length) out.push(`${kept.dark.join(",\n")} {${body}}`);
    if (kept.light.length) light.push(`  ${kept.light.join(", ")} {${body}}`);
  }
  if (light.length)
    out.push(`@media (prefers-color-scheme: light) {\n${light.join("\n")}\n}`);
  return `${out.join("\n")}\n`;
}

if (import.meta.main) {
  await Bun.write(PHONE_CSS, phoneBoardCss(await Bun.file(DESKTOP_CSS).text()));
  console.log(`Wrote ${PHONE_CSS}`);
}
