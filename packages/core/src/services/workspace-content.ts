/**
 * How a session reads and writes the journal. Every session that reads it pays
 * for the whole file on every model call after, so entries stay short and the
 * detail lives in artifacts; `daedalus-compact-workspace journal` moves old
 * entries to `journal/`.
 */
function journalStep(journal: string, archive: string, artifacts: string) {
  return `\`${journal}\` records decisions, blockers, questions and handoffs, newest last. When prior activity matters, read its "Standing decisions" section and the last few entries; older entries are in \`${archive}\`, so grep there for history. An entry is a dated \`##\` heading and at most 5 one-line bullets: what was decided, what changed, what is blocked, what waits on whom. Put evidence, findings, tables, command output and long reasoning in a file under \`${artifacts}\` and link it from the entry. Do not restate the brief or earlier entries.`;
}

